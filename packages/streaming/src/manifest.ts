import { type ChunkId, chunkKey } from './grid.ts'

/** A chunk file and what it costs once loaded. */
export interface ChunkAsset {
  /** Where the asset is fetched from. */
  url: string
  /** Content hash of the asset; a persistent cache uses it to tell versions apart. */
  hash: string
  /** Estimated GPU memory once loaded, in bytes. Reserved against the budget before the load starts. */
  gpuBytes: number
  /** Estimated RAM once loaded, in bytes. Reserved against the budget before the load starts. */
  ramBytes: number
}

/** One chunk of the world, as listed in the manifest. Its own asset is the full-detail one. */
export interface ManifestChunk extends ChunkId, ChunkAsset {
  /**
   * Low-detail version of the chunk. `createStreamer` ignores it: run a second streamer over
   * `lodManifest` with a larger radius, as `streamingPlugin` of `@ceiba/babylon` does.
   */
  lod?: ChunkAsset
}

/** The world manifest JSON generated by the asset pipeline. A chunk that is not listed does not exist. */
export interface WorldManifest {
  /** Format version. */
  version: 1
  /** Side of a chunk, in metres. */
  chunkSize: number
  chunks: ManifestChunk[]
}

/** Checks parsed JSON against the manifest format and returns it typed. Throws on the first problem found. */
export function validateManifest(data: unknown): WorldManifest {
  const fail = (message: string): never => {
    throw new Error(`invalid world manifest: ${message}`)
  }
  const bytes = (value: unknown) => typeof value === 'number' && Number.isFinite(value) && value >= 0
  const asset = (value: ChunkAsset, at: string) => {
    if (typeof value.url !== 'string' || !value.url) fail(`${at}: url must be a non-empty string`)
    if (typeof value.hash !== 'string' || !value.hash) fail(`${at}: hash must be a non-empty string`)
    if (!bytes(value.gpuBytes) || !bytes(value.ramBytes)) fail(`${at}: gpuBytes and ramBytes must be numbers >= 0`)
  }
  if (typeof data !== 'object' || data === null) fail('not an object')
  const manifest = data as WorldManifest
  if (manifest.version !== 1) fail('version must be 1')
  if (!bytes(manifest.chunkSize) || manifest.chunkSize === 0) fail('chunkSize must be a positive number')
  if (!Array.isArray(manifest.chunks)) fail('chunks must be an array')
  const seen = new Set<string>()
  for (const [i, chunk] of manifest.chunks.entries()) {
    const at = `chunks[${i}]`
    if (typeof chunk !== 'object' || chunk === null) fail(`${at} is not an object`)
    if (!Number.isInteger(chunk.cx) || !Number.isInteger(chunk.cz)) fail(`${at}: cx and cz must be integers`)
    asset(chunk, at)
    if (chunk.lod !== undefined) {
      if (typeof chunk.lod !== 'object' || chunk.lod === null) fail(`${at}.lod is not an object`)
      asset(chunk.lod, `${at}.lod`)
    }
    if (seen.has(chunkKey(chunk))) fail(`${at}: duplicate chunk ${chunkKey(chunk)}`)
    seen.add(chunkKey(chunk))
  }
  return manifest
}

/** The same world with every chunk replaced by its `lod` asset. Chunks without one are left out. */
export function lodManifest(manifest: WorldManifest): WorldManifest {
  const chunks = manifest.chunks.flatMap(({ cx, cz, lod }) => (lod ? [{ cx, cz, ...lod }] : []))
  return { ...manifest, chunks }
}
